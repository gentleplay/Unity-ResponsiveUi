namespace FDPlus.IphoneDuo
{
    /// <summary>
    /// UIKit <c>UIInterfaceOrientation</c> values (note: UIKit Landscape Right is Unity's
    /// <c>ScreenOrientation.LandscapeLeft</c> and the reverse).
    /// </summary>
    public enum IphoneDuoInterfaceOrientation
    {
        Unknown = 0,
        Portrait = 1,
        PortraitUpsideDown = 2,
        LandscapeRight = 3,
        LandscapeLeft = 4,
    }
}
